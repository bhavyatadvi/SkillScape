export function detectCurrentDomain(careerProfile) {
  if (!careerProfile) return 'general';
  const searchText = `${careerProfile.degree || ''} ${careerProfile.broadField || ''} ${careerProfile.specialization || ''} ${careerProfile.currentOccupation || ''} ${careerProfile.currentRole || ''} ${careerProfile.currentIndustry || ''}`.toLowerCase();
  for (const [domain, keywords] of Object.entries(CAREER_DOMAINS)) {
    if (keywords.some(k => searchText.includes(k.toLowerCase()))) {
      return domain;
    }
  }
  return 'general';
}

export function generateCandidateCareers(careerProfile) {
  const domain = detectCurrentDomain(careerProfile);
  return CAREERS.map(c => ({
    ...c,
    baseDistance: c.transferableFromDomains?.[domain] ?? 3,
    score: 0,
  }));
}
